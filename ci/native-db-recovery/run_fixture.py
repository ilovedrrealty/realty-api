"""Run the portable backup and restore against this container's synthetic databases."""

from contextlib import closing
import hashlib
import json
import os
from pathlib import Path
import secrets
import sys
from unittest.mock import patch

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.asymmetric import rsa
import psycopg2
from psycopg2 import sql


TOOLS = Path(__file__).resolve().parent
LOCAL = '127.0.0.1'
EMPTY_TABLE = 'research_workspaces'
DB = 'postgres'
RESTORE_DB = 'fixture_restore'
ADMIN = 'fixture_admin'
OWNER = 'fixture_owner'
READ_ROLE = 'fixture_reader'
BIN = Path('/usr/lib/postgresql/17/bin')


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def verify_overlay():
    manifest = json.loads((TOOLS / 'overlay-manifest.json').read_text(encoding='utf-8'))
    require(set(manifest['files_sha256_lf']) == {'capture_fixture_source.py', 'archive_fixture_source.py', 'catalog.sql'},
            'OVERLAY_FILE_SET')
    for name, expected in manifest['files_sha256_lf'].items():
        require(hashlib.sha256((TOOLS / name).read_bytes()).hexdigest() == expected, 'OVERLAY_HASH')
    sys.path.insert(0, str(TOOLS))
    return manifest


def make_fixture(config, tables, password):
    with closing(psycopg2.connect(**config)) as maintenance:
        maintenance.autocommit = True
        with maintenance.cursor() as cursor:
            cursor.execute('CREATE DATABASE fixture_restore')
            cursor.execute('CREATE ROLE fixture_owner LOGIN SUPERUSER PASSWORD %s', (password,))
            cursor.execute('CREATE ROLE fixture_reader NOLOGIN')
    special = {'users', 'leads', 'alembic_version', 'professional_profiles'}
    with closing(psycopg2.connect(**config)) as source, source, source.cursor() as cursor:
        for table in sorted(set(tables) - special):
            identifier = sql.Identifier(table)
            cursor.execute(sql.SQL('CREATE TABLE public.{} (id int PRIMARY KEY)').format(identifier))
            if table != EMPTY_TABLE:
                cursor.execute(sql.SQL('INSERT INTO public.{} VALUES (1)').format(identifier))
        cursor.execute('''
            CREATE TABLE public.users (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
            INSERT INTO public.users DEFAULT VALUES;
            CREATE TABLE public.leads (id int PRIMARY KEY, user_id int NOT NULL REFERENCES public.users(id));
            INSERT INTO public.leads VALUES (1, 1);
            ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
            CREATE POLICY fixture_visibility ON public.leads TO fixture_reader
              USING (user_id::text = current_setting('fixture.reader_id', true));
            GRANT USAGE ON SCHEMA public TO fixture_reader;
            GRANT SELECT ON public.leads TO fixture_reader;
            CREATE TABLE public.alembic_version (version_num text PRIMARY KEY);
            INSERT INTO public.alembic_version VALUES ('synthetic-head');
            CREATE TABLE public.professional_profiles (
              id int PRIMARY KEY, user_id int, review_status text, listing_status text,
              published_data jsonb, published_at timestamptz, draft_data jsonb
            );
            INSERT INTO public.professional_profiles VALUES
              (1, NULL, 'draft', 'hidden', NULL, NULL, '{"public_contact_consent":false}'::jsonb);
        ''')


def metadata(config, catalog_source):
    with closing(psycopg2.connect(**config)) as connection, connection, connection.cursor() as cursor:
        cursor.execute(catalog_source)
        return cursor.fetchone()[0]


def reject_drift(helper, config, owner_config, catalog_source, expected, sql_statement):
    with closing(psycopg2.connect(**config)) as writer, writer, writer.cursor() as cursor:
        cursor.execute(sql_statement)
    with closing(psycopg2.connect(**owner_config, options='-c row_security=off')) as connection, connection, connection.cursor() as cursor:
        connection.set_session(isolation_level='REPEATABLE READ', readonly=True)
        try:
            helper.snapshot_plan(cursor, sql, catalog_source)
        except helper.Stop as error:
            require(str(error) == expected, 'UNEXPECTED_DRIFT_STATUS')
        else:
            raise AssertionError('DRIFT_WAS_ACCEPTED')


def verify_restored(config, tables, expected):
    with closing(psycopg2.connect(**config)) as connection, connection, connection.cursor() as cursor:
        actual = {}
        for table in tables:
            cursor.execute(sql.SQL('SELECT count(*) FROM public.{}').format(sql.Identifier(table)))
            actual[table] = cursor.fetchone()[0]
        require(actual == expected and actual[EMPTY_TABLE] == 0, 'RESTORED_TABLE_COUNTS')
        cursor.execute('SELECT id FROM public.leads ORDER BY id')
        require(cursor.fetchall() == [(1,)], 'NEW_COMMIT_APPEARED_IN_RESTORE')
        cursor.execute('SET LOCAL ROLE fixture_reader')
        for reader, expected_visible in (('1', 1), ('2', 0)):
            cursor.execute("SELECT set_config('fixture.reader_id', %s, true)", (reader,))
            cursor.execute('SELECT count(*) FROM public.leads')
            require(cursor.fetchone()[0] == expected_visible, 'RESTORED_RLS_OR_GRANT')
    with closing(psycopg2.connect(**config)) as connection, connection, connection.cursor() as cursor:
        try:
            cursor.execute('INSERT INTO public.leads VALUES (99, 99)')
        except psycopg2.errors.ForeignKeyViolation:
            connection.rollback()
        else:
            raise AssertionError('RESTORE_FOREIGN_KEY_MISSING')


def main():
    require(os.name == 'posix' and Path('/sys/class/net').is_dir()
            and {entry.name for entry in Path('/sys/class/net').iterdir()} == {'lo'}, 'LOOPBACK_ONLY_REQUIRED')
    manifest = verify_overlay()
    import capture_fixture_source as helper
    import archive_fixture_source as archive_format

    fixture = Path(sys.argv[1]).resolve(strict=True)
    password = secrets.token_urlsafe(24)
    config = {'host': str(fixture / 'socket'), 'dbname': DB, 'user': ADMIN, 'connect_timeout': 5}
    owner_config = {'host': LOCAL, 'dbname': DB, 'user': OWNER, 'password': password, 'sslmode': 'verify-full',
                    'sslrootcert': str(fixture / 'ca.crt'), 'connect_timeout': 5}
    catalog_source = (TOOLS / 'catalog.sql').read_text(encoding='utf-8').strip().removesuffix(';')
    make_fixture(config, helper.TABLES, password)
    baseline = metadata(owner_config, catalog_source)
    helper.PROJECT, helper.HEAD = 'synthetic-native-db', 'synthetic-head'
    helper.CATALOG_SHA = baseline['definition_sha256']
    helper.BIN = helper.DEP = BIN
    helper.PG_DUMP = BIN / 'pg_dump'
    helper.PG_RESTORE = BIN / 'pg_restore'
    helper.CERT = fixture / 'ca.crt'
    original_plan, original_process = helper.snapshot_plan, helper.private_process
    observed = set()

    def after_snapshot(*args):
        snapshot, report = original_plan(*args)
        with closing(psycopg2.connect(**config)) as writer, writer, writer.cursor() as cursor:
            cursor.execute('INSERT INTO public.leads VALUES (2, 1)')
        with closing(psycopg2.connect(**config)) as witness, witness, witness.cursor() as cursor:
            cursor.execute('SELECT count(*) FROM public.leads')
            require(cursor.fetchone()[0] == 2, 'SYNTHETIC_CONCURRENT_COMMIT_NOT_OBSERVED')
        observed.add('concurrent_commit')
        return snapshot, report

    def audit_child(command, **opts):
        require('PGPASSWORD' not in opts['env'] and opts['env']['PGHOST'] == LOCAL
                and all(password not in argument for argument in command), 'CHILD_CREDENTIAL_EXPOSURE')
        result = original_process(command, **opts)
        if command[0] == str(helper.PG_DUMP):
            require('--password' in command and opts['payload'] == bytearray(password + '\n', 'utf-8'),
                    'CHILD_CREDENTIAL_PIPE_NOT_USED')
            observed.add('password_pipe')
        elif command[1] == '--list':
            require(b'TABLE DATA public research_workspaces ' in result, 'EMPTY_TABLE_MISSING_FROM_ARCHIVE')
            observed.add('empty_table_toc')
        elif command[1] == '--file=-':
            require(opts['limit'] == 0 and result == bytearray(), 'UNEXPECTED_ARCHIVE_CONTENT_OUTPUT')
            observed.add('full_decode_discarded')
        return result

    with patch.object(helper, 'snapshot_plan', after_snapshot), patch.object(helper, 'private_process', audit_child), \
            patch.object(helper.getpass, 'getpass', return_value=password) as prompt, \
            patch.object(sys.stdin, 'isatty', return_value=True), patch.object(sys.stdout, 'isatty', return_value=True):
        dump, report = helper.capture(LOCAL, OWNER, catalog_source)
        require(prompt.call_count == 1, 'OWNER_PASSWORD_HOOK_NOT_USED')

    require(observed == {'concurrent_commit', 'password_pipe', 'empty_table_toc', 'full_decode_discarded'},
            'CAPTURE_BOUNDARY_INCOMPLETE')
    counts = report['public_table_record_counts']
    require(len(counts) == 21 and counts == {table: int(table != EMPTY_TABLE) for table in helper.TABLES}
            and report['strictly_private_profile_count'] == 1 and report['verified_tls'] is True,
            'SYNTHETIC_CAPTURE_METADATA_MISMATCH')
    key = rsa.generate_private_key(public_exponent=65537, key_size=3072)
    ciphertext = archive_format.seal(dump, key.public_key())
    decrypt = archive_format.unseal(ciphertext, key)
    require(decrypt == dump and ciphertext.startswith(archive_format.MAGIC), 'ENVELOPE_ROUNDTRIP')
    try:
        archive_format.unseal(ciphertext[:-1] + bytes((ciphertext[-1] ^ 1,)), key)
    except InvalidTag:
        pass
    else:
        raise AssertionError('ENVELOPE_TAMPERING_ACCEPTED')

    restored = config | {'dbname': RESTORE_DB}
    restore_env = {'PGHOST': restored['host'], 'PGUSER': ADMIN, 'PGDATABASE': RESTORE_DB,
                   'PGCONNECT_TIMEOUT': '5', 'PGSSLMODE': 'disable', 'LC_ALL': 'C'}
    original_process([str(helper.PG_RESTORE), '--dbname=' + RESTORE_DB, '--no-password', '--no-owner', '--clean',
                      '--if-exists', '--single-transaction'], env=restore_env, payload=decrypt, limit=0, timeout=45, cwd=BIN)
    verify_restored(restored, helper.TABLES, counts)

    reject_drift(helper, config, owner_config, catalog_source, 'PROFILE_PRIVACY_DRIFT',
                 "UPDATE public.professional_profiles SET draft_data='{}'::jsonb")
    reject_drift(helper, config, owner_config, catalog_source, 'PRODUCTION_SCHEMA_DRIFT',
                 'ALTER TABLE public.activity_log ADD COLUMN synthetic_drift boolean')
    result = {'status': 'PASS', 'portable_owner_capture_sha256': manifest['reviewed_capture_sha256'],
              'catalog_source_sha256': manifest['reviewed_catalog_sha256'],
              'archive_format_sha256': manifest['reviewed_archive_format_sha256'],
              'postgres_version_num': report['server_version_num'], 'synthetic_public_tables_count': len(counts),
              'same_snapshot_excludes_second_session_commit': True, 'authenticated_loopback_tls': True,
              'password_through_unnamed_local_pipe': True, 'empty_table_in_toc': True, 'all_data_parsed': True,
              'synthetic_key_recovered_exact_archive': True, 'tampered_ciphertext_rejected': True,
              'restored_counts_fk_and_role_rls': True, 'profile_guard_failed_closed': True,
              'catalog_guard_failed_closed': True, 'windows_owner_console_or_acl_exercised': False}
    print('NATIVE_DB_RECOVERY_SYNTHETIC ' + json.dumps(result, sort_keys=True, separators=(',', ':')))


if __name__ == '__main__':
    main()
