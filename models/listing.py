import uuid
from sqlalchemy import Column, Text, Numeric, Integer, Boolean, Enum as SAEnum, TIMESTAMP, ARRAY, func, ForeignKey
from sqlalchemy.dialects.postgresql import JSONB, UUID
from database import Base

listing_status = SAEnum("draft", "pending_approval", "active", "rejected", "archived", name="listing_status", create_type=True)
listing_type = SAEnum("villa", "apartment", "condo", "land", "commercial", name="listing_type", create_type=True)
transaction_type = SAEnum("sale", "rent", "both", name="transaction_type", create_type=True)


class Listing(Base):
    __tablename__ = "listings"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    title = Column(Text, nullable=False)
    description = Column(Text)
    description_es = Column(Text)
    type = Column(listing_type, nullable=False)
    transaction = Column(transaction_type, nullable=False)
    price = Column(Numeric(12, 2), nullable=False)
    location = Column(Text, nullable=False)
    bedrooms = Column(Integer)
    bathrooms = Column(Numeric(3, 1))
    area_sqft = Column(Integer)
    lot_size_sqft = Column(Integer)
    roi = Column(Numeric(5, 2))
    seller_financing = Column(Boolean, nullable=False, server_default="false")
    hoa = Column(Boolean, nullable=False, server_default="false")
    hoa_fee = Column(Numeric(10, 2))
    tax_exempt = Column(Boolean, nullable=False, server_default="false")
    gated_community = Column(Boolean, nullable=False, server_default="false")
    construction_status = Column(Text)
    year_built = Column(Integer)
    features = Column(ARRAY(Text), server_default="{}")
    maps_url = Column(Text)
    latitude = Column(Numeric(10, 7))
    longitude = Column(Numeric(10, 7))
    tag = Column(Text)
    tags = Column(ARRAY(Text), nullable=False, server_default="{}")
    video_links = Column(ARRAY(Text), nullable=False, server_default="{}")
    tour_3d_url = Column(Text)
    utilities = Column(Text)
    included_utilities = Column(ARRAY(Text), nullable=False, server_default="{}")
    association_fee = Column(Numeric(12, 2))
    deposit_policy = Column(Text)
    images = Column(ARRAY(Text), server_default="{}")
    share_image_url = Column(Text)
    status = Column(listing_status, nullable=False, server_default="pending_approval")
    submitted_by = Column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    owner_id = Column(UUID(as_uuid=True), ForeignKey("users.id"))
    assigned_realtor_id = Column(UUID(as_uuid=True), ForeignKey("users.id"))
    approved_by = Column(UUID(as_uuid=True), ForeignKey("users.id"))
    approved_at = Column(TIMESTAMP(timezone=True))
    rejection_reason = Column(Text)
    is_deal             = Column(Boolean, nullable=False, server_default="false")
    deal_discount_value = Column(Numeric(12, 2))
    deal_discount_type  = Column(Text, nullable=False, server_default="pct")
    view_count = Column(Integer, nullable=False, server_default="0")
    co_listing_enabled          = Column(Boolean, nullable=False, server_default="false")
    co_listing_brokerage        = Column(Text)
    co_listing_agent_name       = Column(Text)
    co_listing_agent_contact    = Column(Text)
    co_listing_agent_email      = Column(Text)
    co_listing_brokerage_email  = Column(Text)
    co_listing_brokerage_phone  = Column(Text)
    co_listing_commission_split = Column(Numeric(5, 2))
    co_listing_notes            = Column(Text)
    co_listing_status           = Column(Text)
    source_ref = Column(Text, unique=True)
    currency = Column(Text, nullable=False, server_default="USD")
    price_per_day              = Column(Numeric(12, 2))
    price_per_month            = Column(Numeric(12, 2))
    owner_paypal_email         = Column(Text)
    co_listing_agreement_accepted = Column(Boolean, nullable=False, server_default="false")
    co_listing_agreement_url   = Column(Text)
    created_at = Column(TIMESTAMP(timezone=True), nullable=False, server_default=func.now())
    updated_at = Column(TIMESTAMP(timezone=True), nullable=False, server_default=func.now())
    room_photo_tour_snapshot = Column(JSONB(none_as_null=True))
